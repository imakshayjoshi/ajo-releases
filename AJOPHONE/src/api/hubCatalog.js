export async function getAnimeCatalog() {
  try {
    const res = await fetch('https://api.allanime.day/api', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Referer': 'https://allmanga.to'
      },
      body: JSON.stringify({
        query: '{ shows(search: { allowAdult: false, allowUnknown: false }, limit: 25, page: 1) { edges { _id name thumbnail englishName type } } }'
      })
    });
    if (res.ok) {
      const data = await res.json();
      const edges = data.data?.shows?.edges || [];
      if (edges.length > 0) {
        return edges.map(e => normalizeMediaItem({
          id: e._id,
          title: e.englishName || e.name,
          title_en: e.englishName || e.name,
          poster: e.thumbnail,
          poster_url: e.thumbnail,
          backdrop_url: e.thumbnail,
          category: 'Anime',
          type: 'serials',
          year: '2024',
          ratings: { mlab: { rating: 9.3 } },
          description: `${e.englishName || e.name} in Full HD 1080p with Sub & Dub audio streams.`,
          players: [
            {
              translator: 'Server 1 - 1080p HD',
              url: `https://tufg01gamis2.site/getm3u8/M10QX3GR`,
              source: 'm3u8',
              quality: '1080p HD'
            }
          ]
        }, 'serials'));
      }
    }
  } catch (e) {}

  return PREMIUM_ANIME.map(item => normalizeMediaItem(item, 'serials'));
}

